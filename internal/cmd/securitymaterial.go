// addKeyPairFlags adds the flags of a key pair request (alias, key, subject).
func addKeyPairFlags(c *cobra.Command) {
	c.Flags().String("alias", "", "Keystore alias")
	c.Flags().String("key-type", "RSA", "Key type: "+strings.Join(ops.KeyTypes, ", "))
	c.Flags().Int("key-size", 0, "Key size in bits (default 2048 for RSA and DSA)")
	c.Flags().String("curve", "", "Elliptic curve (EC keys)")
	c.Flags().String("signature-algorithm", "", "Signature algorithm, e.g. SHA256/RSA (default: the tenant's)")
	c.Flags().String("valid-until", "", "Validity end, RFC 3339 date or time (default: one year)")
	c.Flags().String("cn", "", "Common name (CN) of the certificate")
	c.Flags().String("ou", "", "Organizational unit (OU)")
	c.Flags().String("org", "", "Organization (O)")
	c.Flags().String("locality", "", "Locality (L)")
	c.Flags().String("state", "", "State (ST)")
	c.Flags().String("country", "", "Two-letter country code (C)")
	c.Flags().String("email", "", "E-mail address")
	c.Flags().Bool("update", false, "Replace an existing entry with the same alias")
}

func keyPairRequest(cmd *cobra.Command) (cpi.KeyPairRequest, error) {
	r := cpi.KeyPairRequest{Alias: config.GetString(cmd, "alias"), KeyType: config.GetString(cmd, "key-type"), KeySize: config.GetInt(cmd, "key-size"),
		EllipticCurve: config.GetString(cmd, "curve"), SignatureAlgorithm: config.GetString(cmd, "signature-algorithm"),
		CommonName: config.GetString(cmd, "cn"), OrganizationUnit: config.GetString(cmd, "ou"), Organization: config.GetString(cmd, "org"),
		Locality: config.GetString(cmd, "locality"), State: config.GetString(cmd, "state"), Country: config.GetString(cmd, "country"),
		Email: config.GetString(cmd, "email")}
	if v := config.GetString(cmd, "valid-until"); v != "" {
		t, err := time.Parse(time.RFC3339, v)
		if err != nil {
			t, err = time.Parse(time.DateOnly, v)
		}
		if err != nil {
			return r, output.Usagef("invalid --valid-until %q (RFC 3339 date or time)", v)
		}
		r.ValidNotAfter = t
	}
	return r, nil
}

func keystoreWriteOutcome(cmd *cobra.Command, res *ops.KeystoreWriteResult, err error) error {
	if res != nil {
		output.SetResult(cmd.Context(), res)
		msg := fmt.Sprintf("%s %s", res.Alias, strings.ToLower(res.Action))
		if res.Entry != nil {
			msg += fmt.Sprintf(" (%s, valid until %s)", res.Entry.SubjectDN, res.Entry.ValidNotAfter.Format(time.DateOnly))
		}
		log.Info().Msg(msg)
		if res.Warning != "" {
			log.Warn().Msg(res.Warning)
		}
	}
	return err
}

// keystoreMaterialCommands are the keystore commands beyond list, export and
// import: delete, key pair and SSH key generation, CSR, certificate chain,
// SSH public key and history.
func keystoreMaterialCommands() []*cobra.Command {
	del := &cobra.Command{
		Use: "delete", Short: "Delete an entry of the system keystore (requires --confirm)", SilenceUsage: true,
		Example: `  cpictl keystore delete --alias partner_acme_old --confirm`,
		RunE: func(cmd *cobra.Command, args []string) error {
			alias := config.GetString(cmd, "alias")
			if !config.GetBool(cmd, "confirm") {
				return output.Usagef("deleting keystore entry %q breaks integration flows that use it; repeat with --confirm", alias)
			}
			res, err := ops.DeleteKeystoreEntry(tenantExecuter(cmd), alias)
			if err != nil {
				return err
			}
			output.SetResult(cmd.Context(), res)
			log.Info().Msgf("%s deleted (%s %s)", res.Deleted.Alias, res.Deleted.Type, res.Deleted.SubjectDN)
			return nil
		},
	}
	del.Flags().String("alias", "", "Keystore alias")
	del.Flags().Bool("confirm", false, "Confirm the deletion")

	genKey := &cobra.Command{
		Use: "generate-key-pair", Short: "Have the tenant generate a key pair (self-signed; then csr and upload-chain)", SilenceUsage: true,
		Long: `The tenant generates the key pair; the private key never leaves it. The
certificate is self-signed: get it signed with 'keystore csr' and upload the
CA's answer with 'keystore upload-chain'.`,
		Example: `  cpictl keystore generate-key-pair --alias client_cert --cn cpi-client.example.com --org "Example AG" --country DE --valid-until 2027-12-31`,
		RunE: func(cmd *cobra.Command, args []string) error {
			r, err := keyPairRequest(cmd)
			if err != nil {
				return err
			}
			res, err := ops.GenerateKeyPair(tenantExecuter(cmd), r, config.GetBool(cmd, "update"), time.Now())
			return keystoreWriteOutcome(cmd, res, err)
		},
	}
	addKeyPairFlags(genKey)

	genSSH := &cobra.Command{
		Use: "generate-ssh-key", Short: "Create an SSH key: generated by the tenant, or imported from an OpenSSH key file", SilenceUsage: true,
		Long: `Without --ssh-file the tenant generates the key; with --ssh-file an existing
OpenSSH private key is imported (its password from --password-env,
--password-file or --password-stdin, never a flag value). Hand the public key
to the SFTP server with 'keystore ssh-public-key'.`,
		Example: `  cpictl keystore generate-ssh-key --alias sftp_partner --cn sftp_partner
  SSH_PW=... cpictl keystore generate-ssh-key --alias sftp_partner --cn sftp_partner --ssh-file id_rsa --password-env SSH_PW`,
		RunE: func(cmd *cobra.Command, args []string) error {
			r, err := keyPairRequest(cmd)
			if err != nil {
				return err
			}
			var file []byte
			if p := config.GetString(cmd, "ssh-file"); p != "" {
				if file, err = os.ReadFile(p); err != nil {
					return output.Usagef("%v", err)
				}
			}
			var pw *ops.SecretSource
			if src := secretSource(cmd, "password"); src.Env != "" || src.File != "" || src.Stdin != nil {
				pw = &src
			}
			res, err := ops.GenerateSSHKey(tenantExecuter(cmd), r, file, pw, config.GetBool(cmd, "update"), time.Now())
			return keystoreWriteOutcome(cmd, res, err)
		},
	}
	addKeyPairFlags(genSSH)
	genSSH.Flags().String("ssh-file", "", "Import this OpenSSH private key file instead of generating a key")
	addSecretFlags(genSSH, "password", "password of the SSH key file")

	csr := &cobra.Command{
		Use: "csr", Short: "Create a certificate signing request (PKCS#10, PEM) for a key pair", SilenceUsage: true,
		Example: `  cpictl keystore csr --alias client_cert --out client_cert.csr`,
		RunE: func(cmd *cobra.Command, args []string) error {
			res, err := ops.CertificateSigningRequest(tenantExecuter(cmd), config.GetString(cmd, "alias"))
			if err != nil {
				return err
			}
			if out := config.GetString(cmd, "out"); out != "" {
				if err := os.WriteFile(out, []byte(res.PEM), 0644); err != nil {
					return err
				}
				log.Info().Msgf("Signing request for %s (%s) written to %s", res.Alias, res.Subject, out)
				output.SetResult(cmd.Context(), map[string]any{"file": out, "alias": res.Alias, "subject": res.Subject})
				return nil
			}
			if outputFormat(cmd) == output.FormatJSON {
				output.SetResult(cmd.Context(), res)
				return nil
			}
			_, err = fmt.Fprint(cmd.OutOrStdout(), res.PEM)
			return err
		},
	}
	csr.Flags().String("alias", "", "Key pair alias")
	csr.Flags().String("out", "", "Write the PEM to this file instead of stdout")

	chain := &cobra.Command{
		Use: "chain", Short: "Show the certificate chain of a key pair", SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			res, err := ops.GetCertificateChain(tenantExecuter(cmd), config.GetString(cmd, "alias"))
			if err != nil {
				return err
			}
			output.SetResult(cmd.Context(), res)
			for _, c := range res.Certificates {
				log.Info().Msgf("%d %s (issuer %s) valid until %s", c.Index, c.SubjectDN, c.IssuerDN, c.ValidNotAfter.Format(time.DateOnly))
			}
			return nil
		},
	}
	chain.Flags().String("alias", "", "Key pair alias")

	upload := &cobra.Command{
		Use: "upload-chain", Short: "Replace the certificate of a key pair with a CA-signed chain (PEM)", SilenceUsage: true,
		Long: `Upload the CA's answer to 'keystore csr': a PEM file with the key pair's
signed certificate first, then the intermediate and root certificates.`,
		Example: `  cpictl keystore upload-chain --alias client_cert --file client_cert_chain.pem`,
		RunE: func(cmd *cobra.Command, args []string) error {
			data, err := os.ReadFile(config.GetString(cmd, "file"))
			if err != nil {
				return output.Usagef("%v", err)
			}
			res, err := ops.UploadCertificateChain(tenantExecuter(cmd), config.GetString(cmd, "alias"), data)
			if err != nil {
				return err
			}
			output.SetResult(cmd.Context(), res)
			for _, c := range res.Certificates {
				log.Info().Msgf("%s (issuer %s) valid until %s", c.Subject, c.Issuer, c.NotAfter.Format(time.DateOnly))
			}
			log.Info().Msgf("Certificate chain of %s replaced (%d certificate(s))", res.Alias, len(res.Certificates))
			return nil
		},
	}
	upload.Flags().String("alias", "", "Key pair alias")
	upload.Flags().String("file", "", "PEM file with the certificate chain")

	sshPub := &cobra.Command{
		Use: "ssh-public-key", Short: "Print the public key of an entry in OpenSSH format (for authorized_keys)", SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			alias := config.GetString(cmd, "alias")
			key, err := ops.SSHPublicKey(tenantExecuter(cmd), alias)
			if err != nil {
				return err
			}
			if outputFormat(cmd) == output.FormatJSON {
				output.SetResult(cmd.Context(), map[string]string{"alias": alias, "publicKey": key})
				return nil
			}
			_, err = fmt.Fprintln(cmd.OutOrStdout(), key)
			return err
		},
	}
	sshPub.Flags().String("alias", "", "Keystore alias")

	history := &cobra.Command{
		Use: "history", Short: "List former versions of keystore entries (replaced by renewals or updates)", SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			entries, err := ops.KeystoreHistory(tenantExecuter(cmd), config.GetString(cmd, "alias"))
			if err != nil {
				return err
			}
			output.SetResult(cmd.Context(), map[string]any{"entries": entries})
			for _, e := range entries {
				until := ""
				if e.ActiveUntil != nil {
					until = e.ActiveUntil.Format(time.DateOnly)
				}
				log.Info().Msgf("%-30s %-10s %s  active until %s  %s", e.Alias, e.Type, e.ValidNotAfter.Format(time.DateOnly), until, e.SubjectDN)
			}
			log.Info().Msgf("%d history entr(ies)", len(entries))
			return nil
		},
	}
	history.Flags().String("alias", "", "Only versions of this alias")

	return []*cobra.Command{del, genKey, genSSH, csr, chain, upload, sshPub, history}
}

func NewPGPCommand() *cobra.Command {
	c := &cobra.Command{
		Use:   "pgp",
		Short: "List PGP keyrings and keys, export or replace the public keyring",
	}
	list := &cobra.Command{
		Use: "list", Short: "List PGP public and secret keys (metadata, never key material)", SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			o, err := ops.ListPGP(tenantExecuter(cmd))
			if err != nil {
				return err
			}
			output.SetResult(cmd.Context(), o)
			for _, ring := range []struct {
				kind string
				keys []cpi.PgpKey
			}{{"public", o.PublicKeys}, {"secret", o.SecretKeys}} {
				kind := ring.kind
				for _, k := range ring.keys {
					until := ""
					if k.ValidUntil != nil {
						until = k.ValidUntil.Format(time.DateOnly)
					}
					log.Info().Msgf("%-6s %-18s %-8s %s %s", kind, k.KeyID, k.Validity, until, k.PrimaryUserID)
				}
			}
			log.Info().Msgf("%d public, %d secret key(s)", len(o.PublicKeys), len(o.SecretKeys))
			return nil
		},
	}
	export := &cobra.Command{
		Use: "export-public", Short: "Download the public keyring", SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			data, err := ops.ExportPGPPublicKeyring(tenantExecuter(cmd))
			if err != nil {
				return err
			}
			out := config.GetString(cmd, "out")
			if out == "" {
				return output.Usagef("--out is required (the keyring is binary)")
			}
			if err := os.WriteFile(out, data, 0644); err != nil {
				return err
			}
			output.SetResult(cmd.Context(), map[string]any{"file": out, "bytes": len(data)})
			log.Info().Msgf("Public keyring written to %s (%d bytes)", out, len(data))
			return nil
		},
	}
	export.Flags().String("out", "", "File to write the keyring to")
	imp := &cobra.Command{
		Use: "import-public", Short: "Replace the public keyring with a file of OpenPGP public keys (requires --confirm)", SilenceUsage: true,
		Long: `Uploads a public keyring (binary or ASCII-armored). It replaces the tenant's
public keyring: keys missing from the file are gone afterwards, so export the
current keyring first and merge locally (e.g. gpg --import, --export).`,
		Example: `  cpictl pgp export-public --out pubring.gpg
  cpictl pgp import-public --file pubring-new.gpg --confirm`,
		RunE: func(cmd *cobra.Command, args []string) error {
			if !config.GetBool(cmd, "confirm") {
				return output.Usagef("importing replaces the tenant's public keyring; repeat with --confirm")
			}
			data, err := os.ReadFile(config.GetString(cmd, "file"))
			if err != nil {
				return output.Usagef("%v", err)
			}
			res, err := ops.ImportPGPPublicKeyring(tenantExecuter(cmd), data)
			if err != nil {
				return err
			}
			output.SetResult(cmd.Context(), res)
			log.Info().Msgf("Public keyring uploaded (%d bytes, %d key(s))", res.Bytes, len(res.PublicKeys))
			return nil
		},
	}
	imp.Flags().String("file", "", "Keyring file")
	imp.Flags().Bool("confirm", false, "Confirm replacing the public keyring")
	c.AddCommand(list, export, imp)
	return c
}

func addReferenceFlags(c *cobra.Command) {
	c.Flags().String("name", "", "Name of the artifact reference")
	c.Flags().String("description", "", "Description")
	c.Flags().String("type", "INTEGRATION_FLOW", "Artifact type, e.g. INTEGRATION_FLOW, VALUE_MAPPING, DATA_STORE")
	c.Flags().String("attribute", "Name", "Condition attribute: Name or ID")
	c.Flags().String("value", "", "Condition value (artifact name/ID or regular expression)")
	c.Flags().String("condition", "EXACT_MATCH", "Condition type: EXACT_MATCH or REGULAR_EXPRESSION")
}

func referenceFromFlags(cmd *cobra.Command) cpi.ArtifactReference {
	return cpi.ArtifactReference{Name: config.GetString(cmd, "name"), Description: config.GetString(cmd, "description"), Type: config.GetString(cmd, "type"),
		ConditionAttribute: config.GetString(cmd, "attribute"), ConditionValue: config.GetString(cmd, "value"), ConditionType: config.GetString(cmd, "condition")}
}

func accessPolicyOutcome(cmd *cobra.Command, res *ops.AccessPolicyResult, err error) error {
	if res != nil {
		output.SetResult(cmd.Context(), res)
		log.Info().Msgf("%s %s %s", res.ID, strings.ToLower(res.Action), res.Detail)
	}
	return err
}

func NewAccessPoliciesCommand() *cobra.Command {
	c := &cobra.Command{
		Use:   "access-policies",
		Short: "List, create and delete access policies and their artifact references",
		Long: `Access policies restrict who may read or change artifacts: an artifact
matched by a policy's artifact references is accessible only to users with the
policy's role (a role of the subaccount, e.g. assigned through a role
collection). Deleting a policy or a reference lifts the restriction.`,
	}
	list := &cobra.Command{
		Use: "list", Short: "List access policies with their artifact references", SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			policies, err := ops.ListAccessPolicies(tenantExecuter(cmd))
			if err != nil {
				return err
			}
			output.SetResult(cmd.Context(), map[string]any{"accessPolicies": policies})
			for _, p := range policies {
				log.Info().Msgf("%-8s %-30s %s", p.ID, p.RoleName, p.Description)
				for _, r := range p.ArtifactReferences {
					log.Info().Msgf("    %-8s %-20s %s %s %s", r.ID, r.Type, r.ConditionAttribute, r.ConditionType, r.ConditionValue)
				}
			}
			log.Info().Msgf("%d access polic(ies)", len(policies))
			return nil
		},
	}
	create := &cobra.Command{
		Use: "create", Short: "Create an access policy, optionally with one artifact reference", SilenceUsage: true,
		Example: `  cpictl access-policies create --role OrdersTeam --description "Orders flows" --name Orders --value 'Orders_.*' --condition REGULAR_EXPRESSION`,
		RunE: func(cmd *cobra.Command, args []string) error {
			var refs []cpi.ArtifactReference
			if config.GetString(cmd, "value") != "" {
				refs = append(refs, referenceFromFlags(cmd))
			}
			res, err := ops.CreateAccessPolicy(tenantExecuter(cmd), config.GetString(cmd, "role"), config.GetString(cmd, "policy-description"), refs)
			return accessPolicyOutcome(cmd, res, err)
		},
	}
	create.Flags().String("role", "", "Role name")
	create.Flags().String("policy-description", "", "Description of the policy")
	addReferenceFlags(create)
	del := &cobra.Command{
		Use: "delete", Short: "Delete an access policy with its references (requires --confirm)", SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			id := config.GetString(cmd, "id")
			if !config.GetBool(cmd, "confirm") {
				return output.Usagef("deleting access policy %s lifts its access restriction; repeat with --confirm", id)
			}
			res, err := ops.DeleteAccessPolicy(tenantExecuter(cmd), id)
			return accessPolicyOutcome(cmd, res, err)
		},
	}
	del.Flags().String("id", "", "Access policy ID")
	del.Flags().Bool("confirm", false, "Confirm the deletion")
	addRef := &cobra.Command{
		Use: "add-reference", Short: "Add an artifact reference to an access policy", SilenceUsage: true,
		Example: `  cpictl access-policies add-reference --policy-id 1001 --name Returns --value Returns_In`,
		RunE: func(cmd *cobra.Command, args []string) error {
			res, err := ops.AddArtifactReference(tenantExecuter(cmd), config.GetString(cmd, "policy-id"), referenceFromFlags(cmd))
			return accessPolicyOutcome(cmd, res, err)
		},
	}
	addRef.Flags().String("policy-id", "", "Access policy ID")
	addReferenceFlags(addRef)
	delRef := &cobra.Command{
		Use: "delete-reference", Short: "Delete an artifact reference (requires --confirm)", SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			id := config.GetString(cmd, "id")
			if !config.GetBool(cmd, "confirm") {
				return output.Usagef("deleting artifact reference %s lifts its access restriction; repeat with --confirm", id)
			}
			res, err := ops.DeleteArtifactReference(tenantExecuter(cmd), id)
			return accessPolicyOutcome(cmd, res, err)
		},
	}
	delRef.Flags().String("id", "", "Artifact reference ID")
	delRef.Flags().Bool("confirm", false, "Confirm the deletion")
	c.AddCommand(list, create, del, addRef, delRef)
	return c
}

func NewAuditLogCommand() *cobra.Command {
	c := &cobra.Command{
		Use:   "audit-log",
		Short: "Show the tenant's audit log (who changed what, newest first)",
		Long: `Reads /api/v1/AuditLogs. The credentials need a role that may read the audit
log; without it the tenant answers 403 and the result says missing_role
(exit code 0). 'cpictl doctor' shows whether the role is there.`,
		Example: `  cpictl audit-log --since 24h
  cpictl audit-log --since 7d --user dev@example.com --object Orders`,
		SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			since, err := ops.ParseTimeArg(config.GetString(cmd, "since"), time.Now())
			if err != nil {
				return output.Usagef("invalid --since: %v", err)
			}
			res, err := ops.ListAuditLogs(tenantExecuter(cmd), since, config.GetInt(cmd, "top"), config.GetString(cmd, "user"), config.GetString(cmd, "object"))
			if err != nil {
				return err
			}
			output.SetResult(cmd.Context(), res)
			if res.Status != "" {
				log.Warn().Msg(res.Hint)
				return nil
			}
			for _, e := range res.Entries {
				log.Info().Msgf("%s %-10s %-30s %-20s %s", e.Timestamp.Local().Format("2006-01-02 15:04:05"), e.Action, e.ObjectName, e.ObjectType, e.UserName)
			}
			log.Info().Msgf("%d entr(ies)", len(res.Entries))
			return nil
		},
	}
	c.Flags().String("since", "24h", "Entries after this time (duration like 24h or 7d, or RFC 3339)")
	c.Flags().Int("top", 200, "At most this many entries")
	c.Flags().String("user", "", "Only entries of this user")
	c.Flags().String("object", "", "Only entries whose object name contains this text")
	return c
}

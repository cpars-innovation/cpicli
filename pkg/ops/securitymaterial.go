// systemEntry returns the entry of the system keystore with alias (nil if
// there is none).
func systemEntry(sec *cpi.Security, alias string) (*cpi.KeystoreEntry, error) {
	entries, err := sec.KeystoreEntries("system")
	if err != nil {
		return nil, err
	}
	for i := range entries {
		if entries[i].Alias == alias {
			return &entries[i], nil
		}
	}
	return nil, nil
}

// KeystoreDeleteResult is the outcome of DeleteKeystoreEntry.
type KeystoreDeleteResult struct {
	Deleted cpi.KeystoreEntry `json:"deleted"`
}

// DeleteKeystoreEntry deletes an entry of the system keystore. Entries owned
// by SAP cannot be deleted; a missing alias is a usage error.
func DeleteKeystoreEntry(exe *httpclnt.HTTPExecuter, alias string) (*KeystoreDeleteResult, error) {
	if alias == "" {
		return nil, output.Usagef("alias is required")
	}
	sec := cpi.NewSecurity(exe)
	e, err := systemEntry(sec, alias)
	if err != nil {
		return nil, err
	}
	if e == nil {
		return nil, output.Usagef("keystore entry %s not found", alias)
	}
	if strings.EqualFold(e.Owner, "SAP") {
		return nil, output.Usagef("keystore entry %s is owned by SAP and cannot be deleted", alias)
	}
	if err := sec.DeleteKeystoreEntry(alias); err != nil {
		return nil, err
	}
	return &KeystoreDeleteResult{Deleted: *e}, nil
}

// isKeyPair reports whether a keystore entry type has a private key
// (KeyPair, SSHKey).
func isKeyPair(entryType string) bool {
	t := strings.ToLower(strings.ReplaceAll(entryType, " ", ""))
	return t == "keypair" || t == "sshkey"
}

// KeyTypes are the key algorithms the tenant generates.
var KeyTypes = []string{"RSA", "DSA", "EC"}

// checkKeyPairRequest fills defaults (RSA 2048, one year) and validates.
func checkKeyPairRequest(r *cpi.KeyPairRequest, now time.Time) error {
	if r.Alias == "" {
		return output.Usagef("alias is required")
	}
	if r.CommonName == "" {
		return output.Usagef("common name is required")
	}
	if r.KeyType == "" {
		r.KeyType = "RSA"
	}
	r.KeyType = strings.ToUpper(r.KeyType)
	if !slices.Contains(KeyTypes, r.KeyType) {
		return output.Usagef("invalid key type %q (valid: %s)", r.KeyType, strings.Join(KeyTypes, ", "))
	}
	if r.KeySize == 0 && r.KeyType != "EC" {
		r.KeySize = 2048
	}
	if r.KeyType == "RSA" && r.KeySize < 2048 {
		return output.Usagef("RSA keys need at least 2048 bits")
	}
	if r.ValidNotAfter.IsZero() {
		r.ValidNotAfter = now.AddDate(1, 0, 0)
	}
	if !r.ValidNotAfter.After(now) {
		return output.Usagef("valid-until must be in the future")
	}
	if r.Country != "" && len(r.Country) != 2 {
		return output.Usagef("country must be a two-letter code, e.g. DE")
	}
	return nil
}

// KeystoreWriteResult is the outcome of a key generation.
type KeystoreWriteResult struct {
	Alias   string             `json:"alias"`
	Action  string             `json:"action"` // CREATED or UPDATED
	Entry   *cpi.KeystoreEntry `json:"entry,omitempty"`
	Warning string             `json:"warning,omitempty"`
}

func keystoreWrite(sec *cpi.Security, alias string, update bool, write func() error) (*KeystoreWriteResult, error) {
	existing, err := systemEntry(sec, alias)
	if err != nil {
		return nil, err
	}
	if existing != nil && !update {
		return nil, output.Usagef("keystore entry %s already exists (use update to replace it)", alias)
	}
	if existing != nil && strings.EqualFold(existing.Owner, "SAP") {
		return nil, output.Usagef("keystore entry %s is owned by SAP and cannot be replaced", alias)
	}
	if err := write(); err != nil {
		return nil, err
	}
	res := &KeystoreWriteResult{Alias: alias, Action: "CREATED"}
	if existing != nil {
		res.Action = "UPDATED"
	}
	if res.Entry, err = systemEntry(sec, alias); err != nil || res.Entry == nil {
		res.Warning = "the tenant accepted the request, but the entry could not be read back"
	}
	return res, nil
}

// GenerateKeyPair has the tenant generate a key pair (self-signed
// certificate) in the system keystore. The private key stays on the tenant;
// get a CA-signed certificate with CertificateSigningRequest and
// UploadCertificateChain.
func GenerateKeyPair(exe *httpclnt.HTTPExecuter, r cpi.KeyPairRequest, update bool, now time.Time) (*KeystoreWriteResult, error) {
	if err := checkKeyPairRequest(&r, now); err != nil {
		return nil, err
	}
	sec := cpi.NewSecurity(exe)
	return keystoreWrite(sec, r.Alias, update, func() error { return sec.GenerateKeyPair(r, update) })
}

// GenerateSSHKey creates an SSH key in the system keystore: generated by the
// tenant, or imported from an OpenSSH private key file (sshFile, optionally
// protected by the password from password). The key and the password are
// never logged or returned.
func GenerateSSHKey(exe *httpclnt.HTTPExecuter, r cpi.KeyPairRequest, sshFile []byte, password *SecretSource, update bool, now time.Time) (*KeystoreWriteResult, error) {
	if err := checkKeyPairRequest(&r, now); err != nil {
		return nil, err
	}
	req := cpi.SSHKeyRequest{KeyPairRequest: r, SSHFile: string(sshFile)}
	if password != nil {
		pw, err := password.Resolve("SSH key password")
		if err != nil {
			return nil, err
		}
		req.Password = pw
	}
	sec := cpi.NewSecurity(exe)
	return keystoreWrite(sec, r.Alias, update, func() error { return sec.GenerateSSHKey(req, update) })
}

// CSRResult is a certificate signing request of a key pair.
type CSRResult struct {
	Alias   string `json:"alias"`
	Subject string `json:"subject,omitempty"`
	PEM     string `json:"pem"`
}

// CertificateSigningRequest returns a PKCS#10 signing request for a key pair
// of the system keystore, as PEM (send it to the CA; upload the answer with
// UploadCertificateChain).
func CertificateSigningRequest(exe *httpclnt.HTTPExecuter, alias string) (*CSRResult, error) {
	if alias == "" {
		return nil, output.Usagef("alias is required")
	}
	sec := cpi.NewSecurity(exe)
	e, err := systemEntry(sec, alias)
	if err != nil {
		return nil, err
	}
	switch {
	case e == nil:
		return nil, output.Usagef("keystore entry %s not found", alias)
	case strings.EqualFold(e.Owner, "SAP"):
		return nil, output.Usagef("keystore entry %s is owned by SAP; create a signing request for your own key pair", alias)
	case !isKeyPair(e.Type):
		return nil, output.Usagef("%s is a %s; a signing request needs a key pair", alias, e.Type)
	}
	raw, err := sec.SigningRequest(alias)
	if err != nil {
		return nil, err
	}
	der := raw
	if block, _ := pem.Decode(raw); block != nil {
		der = block.Bytes
	} else if b, err := base64.StdEncoding.DecodeString(strings.TrimSpace(string(raw))); err == nil {
		der = b
	}
	res := &CSRResult{Alias: alias, PEM: string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE REQUEST", Bytes: der}))}
	if csr, err := x509.ParseCertificateRequest(der); err == nil {
		res.Subject = csr.Subject.String()
	}
	return res, nil
}

// CertificateChain is the chain of a key pair.
type CertificateChain struct {
	Alias        string                 `json:"alias"`
	Certificates []cpi.ChainCertificate `json:"certificates"`
}

// GetCertificateChain lists the certificate chain of a key pair.
func GetCertificateChain(exe *httpclnt.HTTPExecuter, alias string) (*CertificateChain, error) {
	if alias == "" {
		return nil, output.Usagef("alias is required")
	}
	certs, err := cpi.NewSecurity(exe).ChainCertificates(alias)
	if err != nil {
		switch httpclnt.StatusCode(err) {
		case http.StatusNotFound:
			return nil, output.Usagef("keystore entry %s not found", alias)
		case http.StatusBadRequest:
			return nil, output.Usagef("%s has no certificate chain (only key pairs have one): %v", alias, err)
		}
		return nil, err
	}
	slices.SortFunc(certs, func(a, b cpi.ChainCertificate) int { return a.Index - b.Index })
	return &CertificateChain{Alias: alias, Certificates: certs}, nil
}

// ParseCertificates reads all certificates of PEM data (several CERTIFICATE
// blocks) or of one DER certificate.
func ParseCertificates(data []byte) ([]*x509.Certificate, error) {
	var certs []*x509.Certificate
	rest := data
	for {
		var block *pem.Block
		block, rest = pem.Decode(rest)
		if block == nil {
			break
		}
		if block.Type != "CERTIFICATE" {
			return nil, output.Usagef("PEM block is %q, expected CERTIFICATE (private keys are not accepted)", block.Type)
		}
		c, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			return nil, output.Usagef("not a valid X.509 certificate: %v", err)
		}
		certs = append(certs, c)
	}
	if len(certs) > 0 {
		return certs, nil
	}
	c, err := ParseCertificate(data)
	if err != nil {
		return nil, err
	}
	return []*x509.Certificate{c}, nil
}

// ChainUploadResult is the outcome of UploadCertificateChain.
type ChainUploadResult struct {
	Alias        string            `json:"alias"`
	Certificates []CertificateInfo `json:"certificates"`
}

// UploadCertificateChain replaces the certificate of a key pair with a
// CA-signed chain (PEM with the key pair's certificate first, then the
// intermediate and root certificates).
func UploadCertificateChain(exe *httpclnt.HTTPExecuter, alias string, data []byte) (*ChainUploadResult, error) {
	if alias == "" {
		return nil, output.Usagef("alias is required")
	}
	certs, err := ParseCertificates(data)
	if err != nil {
		return nil, err
	}
	sec := cpi.NewSecurity(exe)
	e, err := systemEntry(sec, alias)
	if err != nil {
		return nil, err
	}
	if e == nil {
		return nil, output.Usagef("keystore entry %s not found", alias)
	}
	if !isKeyPair(e.Type) {
		return nil, output.Usagef("%s is a %s; a certificate chain belongs to a key pair", alias, e.Type)
	}
	res := &ChainUploadResult{Alias: alias}
	ders := make([][]byte, 0, len(certs))
	for _, c := range certs {
		ders = append(ders, c.Raw)
		res.Certificates = append(res.Certificates, certificateInfo(c.Subject.CommonName, c))
	}
	if err := sec.UploadCertificateChain(alias, ders); err != nil {
		return nil, err
	}
	return res, nil
}

// SSHPublicKey returns the public key of a keystore entry in OpenSSH format
// (for the authorized_keys file of an SFTP server).
func SSHPublicKey(exe *httpclnt.HTTPExecuter, alias string) (string, error) {
	if alias == "" {
		return "", output.Usagef("alias is required")
	}
	key, err := cpi.NewSecurity(exe).SSHPublicKey(alias)
	if httpclnt.StatusCode(err) == http.StatusNotFound {
		return "", output.Usagef("keystore entry %s not found", alias)
	}
	return key, err
}

// KeystoreHistory lists former versions of keystore entries, newest first.
func KeystoreHistory(exe *httpclnt.HTTPExecuter, alias string) ([]cpi.HistoryKeystoreEntry, error) {
	entries, err := cpi.NewSecurity(exe).HistoryKeystoreEntries()
	if err != nil {
		return nil, err
	}
	out := []cpi.HistoryKeystoreEntry{}
	for _, e := range entries {
		if alias == "" || e.Alias == alias || e.OriginalAlias == alias {
			out = append(out, e)
		}
	}
	slices.SortStableFunc(out, func(a, b cpi.HistoryKeystoreEntry) int { return b.LastModified.Compare(a.LastModified) })
	return out, nil
}

// PGPOverview lists the PGP keyrings and their keys (metadata only).
type PGPOverview struct {
	Keyrings   []cpi.PgpKeyring `json:"keyrings"`
	PublicKeys []cpi.PgpKey     `json:"publicKeys"`
	SecretKeys []cpi.PgpKey     `json:"secretKeys"`
}

// ListPGP lists the PGP keyrings with their keys, user IDs and sub keys.
// Secret keys are listed by their metadata; key material is never read.
func ListPGP(exe *httpclnt.HTTPExecuter) (*PGPOverview, error) {
	sec := cpi.NewSecurity(exe)
	rings, err := sec.PgpKeyrings()
	if err != nil {
		return nil, err
	}
	o := &PGPOverview{Keyrings: rings, PublicKeys: []cpi.PgpKey{}, SecretKeys: []cpi.PgpKey{}}
	for _, r := range rings {
		keys, err := sec.PgpKeys(r.Name)
		if err != nil {
			return nil, fmt.Errorf("keys of PGP keyring %s: %w", r.Name, err)
		}
		if r.Kind == "secret" {
			o.SecretKeys = append(o.SecretKeys, keys...)
		} else {
			o.PublicKeys = append(o.PublicKeys, keys...)
		}
	}
	return o, nil
}

// DefaultPublicKeyring is the name of the tenant's PGP public keyring.
const DefaultPublicKeyring = "pubring"

// ExportPGPPublicKeyring downloads the public keyring (empty if it has no keys).
func ExportPGPPublicKeyring(exe *httpclnt.HTTPExecuter) ([]byte, error) {
	return cpi.NewSecurity(exe).PgpPublicKeyring(DefaultPublicKeyring)
}

// PGPImportResult is the outcome of ImportPGPPublicKeyring.
type PGPImportResult struct {
	Bytes      int          `json:"bytes"`
	PublicKeys []cpi.PgpKey `json:"publicKeys"`
}

// ImportPGPPublicKeyring replaces the public keyring with data (OpenPGP
// public keys, binary or ASCII-armored) and lists the keys afterwards.
// Secret keys are refused.
func ImportPGPPublicKeyring(exe *httpclnt.HTTPExecuter, data []byte) (*PGPImportResult, error) {
	if len(data) == 0 {
		return nil, output.Usagef("the keyring file is empty")
	}
	if strings.Contains(string(data), "PRIVATE KEY BLOCK") {
		return nil, output.Usagef("the file contains a secret key; only public keys can be uploaded")
	}
	sec := cpi.NewSecurity(exe)
	if err := sec.UploadPgpPublicKeyring(DefaultPublicKeyring, data); err != nil {
		return nil, err
	}
	keys, err := sec.PgpKeys(DefaultPublicKeyring)
	if err != nil {
		return nil, err
	}
	return &PGPImportResult{Bytes: len(data), PublicKeys: keys}, nil
}

// ListAccessPolicies lists the access policies with their artifact references.
func ListAccessPolicies(exe *httpclnt.HTTPExecuter) ([]cpi.AccessPolicyDetail, error) {
	return cpi.NewSecurity(exe).AccessPoliciesWithReferences()
}

// AccessPolicyResult is the outcome of an access policy change.
type AccessPolicyResult struct {
	ID     string `json:"id,omitempty"`
	Action string `json:"action"`
	Detail string `json:"detail,omitempty"`
}

func checkReference(r cpi.ArtifactReference) error {
	if r.Name == "" || r.Type == "" || r.ConditionAttribute == "" || r.ConditionValue == "" || r.ConditionType == "" {
		return output.Usagef("an artifact reference needs name, type, condition attribute, condition value and condition type")
	}
	return nil
}

// CreateAccessPolicy creates an access policy for a role, optionally with
// artifact references.
func CreateAccessPolicy(exe *httpclnt.HTTPExecuter, roleName, description string, refs []cpi.ArtifactReference) (*AccessPolicyResult, error) {
	if roleName == "" {
		return nil, output.Usagef("role name is required")
	}
	for _, r := range refs {
		if err := checkReference(r); err != nil {
			return nil, err
		}
	}
	id, err := cpi.NewSecurity(exe).CreateAccessPolicy(roleName, description, refs)
	if err != nil {
		return nil, err
	}
	return &AccessPolicyResult{ID: id, Action: "CREATED", Detail: roleName}, nil
}

func findPolicy(exe *httpclnt.HTTPExecuter, id string) (*cpi.AccessPolicyDetail, error) {
	policies, err := ListAccessPolicies(exe)
	if err != nil {
		return nil, err
	}
	for i := range policies {
		if policies[i].ID == id {
			return &policies[i], nil
		}
	}
	return nil, output.Usagef("access policy %s not found", id)
}

// DeleteAccessPolicy deletes an access policy and its artifact references:
// the artifacts it protected are no longer restricted to the role.
func DeleteAccessPolicy(exe *httpclnt.HTTPExecuter, id string) (*AccessPolicyResult, error) {
	p, err := findPolicy(exe, id)
	if err != nil {
		return nil, err
	}
	if err := cpi.NewSecurity(exe).DeleteAccessPolicy(id); err != nil {
		return nil, err
	}
	return &AccessPolicyResult{ID: id, Action: "DELETED", Detail: fmt.Sprintf("%s, %d artifact reference(s)", p.RoleName, len(p.ArtifactReferences))}, nil
}

// AddArtifactReference adds an artifact reference to an access policy.
func AddArtifactReference(exe *httpclnt.HTTPExecuter, policyID string, r cpi.ArtifactReference) (*AccessPolicyResult, error) {
	if err := checkReference(r); err != nil {
		return nil, err
	}
	if _, err := findPolicy(exe, policyID); err != nil {
		return nil, err
	}
	id, err := cpi.NewSecurity(exe).CreateArtifactReference(policyID, r)
	if err != nil {
		return nil, err
	}
	return &AccessPolicyResult{ID: id, Action: "CREATED", Detail: fmt.Sprintf("%s %s %s %s in policy %s", r.Type, r.ConditionAttribute, r.ConditionType, r.ConditionValue, policyID)}, nil
}

// DeleteArtifactReference deletes an artifact reference of an access policy.
func DeleteArtifactReference(exe *httpclnt.HTTPExecuter, id string) (*AccessPolicyResult, error) {
	policies, err := ListAccessPolicies(exe)
	if err != nil {
		return nil, err
	}
	for _, p := range policies {
		for _, r := range p.ArtifactReferences {
			if r.ID == id {
				if err := cpi.NewSecurity(exe).DeleteArtifactReference(id); err != nil {
					return nil, err
				}
				return &AccessPolicyResult{ID: id, Action: "DELETED", Detail: fmt.Sprintf("%s from policy %s (%s)", r.Name, p.ID, p.RoleName)}, nil
			}
		}
	}
	return nil, output.Usagef("artifact reference %s not found", id)
}

// AuditLogResult lists audit log entries. Status is "missing_role" when the
// credentials may not read the audit log (403).
type AuditLogResult struct {
	Status  string         `json:"status,omitempty"`
	Hint    string         `json:"hint,omitempty"`
	Entries []cpi.AuditLog `json:"entries"`
}

const auditMissingRoleHint = "the tenant refused the audit log (HTTP 403): the service key needs a role that allows reading audit logs; continue without it and tell the user"

// ListAuditLogs reads the audit log since a point in time (newest first, at
// most top entries; 0: 200), optionally only entries of a user or object.
func ListAuditLogs(exe *httpclnt.HTTPExecuter, since time.Time, top int, user, object string) (*AuditLogResult, error) {
	if top <= 0 {
		top = 200
	}
	entries, err := cpi.NewSecurity(exe).AuditLogs(since, top)
	if httpclnt.StatusCode(err) == http.StatusForbidden {
		return &AuditLogResult{Status: TraceMissingRole, Hint: auditMissingRoleHint, Entries: []cpi.AuditLog{}}, nil
	}
	if err != nil {
		return nil, err
	}
	res := &AuditLogResult{Entries: []cpi.AuditLog{}}
	for _, e := range entries {
		if (user == "" || strings.EqualFold(e.UserName, user)) && (object == "" || strings.Contains(strings.ToLower(e.ObjectName), strings.ToLower(object))) {
			res.Entries = append(res.Entries, e)
		}
	}
	return res, nil
}
